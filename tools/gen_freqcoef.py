#!/usr/bin/env python3
"""Generate src/core/FreqCoef.inc from third_party/SMR/envout_pwm.c FreqCoef_to_PWMval().

Reads the live (integer) comparison cascade, i.e. the lines that start with "if (k<=14) return(0);" up to
"else return(4095);", and rewrites every numeric literal as a float literal (f suffix), because the firmware is
built with -fsingle-precision-constant. Nothing else is changed. Usage: gen_freqcoef.py <envout_pwm.c> <out.inc>
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
lines = open(src, encoding="utf-8", errors="replace").read().split("\n")

start = next(i for i, l in enumerate(lines) if l.strip() == "if (k<=14) return(0);")
end = next(i for i in range(start, len(lines)) if lines[i].strip() == "else return(4095);")

pat = re.compile(r"else if \(k<=(\d+)\) \{t=([0-9.]+);b=([0-9.]+);tval=(\d+);bval=(\d+);\}")
rows = []
for l in lines[start + 1:end]:
    m = pat.fullmatch(l.strip())
    if not m:
        sys.exit("unexpected line: " + l)
    rows.append(m.groups())

o = ["// GENERATED by tools/gen_freqcoef.py from third_party/SMR/envout_pwm.c, FreqCoef_to_PWMval(), lines %d to %d."
     % (start + 1, end + 1),
     "// Do not edit by hand. Every literal t, b, tval and bval carries an f suffix (-fsingle-precision-constant).",
     "if (k<=14) return(0);"]
for k, t, b, tv, bv in rows:
    o.append("else if (k<=%s) {t=%sf;b=%sf;tval=%s.0f;bval=%s.0f;}" % (k, t, b, tv, bv))
o.append("else return(4095);")
open(out, "w").write("\n".join(o) + "\n")
print(len(rows), "rows")
